"""
Door voice prompts -> firmware/SmartLab_Master_Portal/door_voice.h

    py make_voice.py                 (Windows: uses the built-in speech voices)
    py make_voice.py --voice "Microsoft David Desktop"

Each phrase below is spoken by Windows' offline text-to-speech, recorded at
16000 Hz, trimmed of leading/trailing silence, compressed (tanh) and
normalised to 98 % of full scale - loud, but with headroom so the amplifier
does not clip - and stored in the door firmware as 8-bit unsigned PCM. Nothing is needed at
the door: no internet, no SD card. Change a phrase or add a name, re-run,
re-flash the door.

Names: one clip per door identity (USERn), said after "Hello". A person
without a clip just hears "Welcome. The door is unlocked."
"""
from __future__ import annotations

import argparse
import array
import math
import pathlib
import subprocess
import tempfile
import wave

RATE = 16000
HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "firmware" / "SmartLab_Master_Portal" / "door_voice.h"
# The same phrases as text, for a tablet page that says them with its own voice.
TEXT_OUT = OUT.with_name("door_voice_text.h")

# id -> phrase. The ids are used by the firmware (VOICE_<ID>).
PHRASES = {
    "BOOT":        "Smart Lab door ready.",
    "WELCOME":     "Welcome to the Smart Lab. Please scan your card, or your Q R code.",
    "VERIFY":      "Thank you. Now please verify with your fingerprint, or your face.",
    "HELLO":       "Hello",
    "WELCOME_IN":  "Welcome. The door is unlocked.",
    "DENIED":      "Access denied.",
    "TIME_UP":     "Time is up.",
    "MISMATCH":    "Your identity does not match.",
    "TRY_AGAIN":   "Please try again.",
    "CLOSE_DOOR":  "Please close the door.",
    "FORCED":      "Warning. Unauthorized entry.",
    "EVACUATE":    "Emergency. Please leave the lab now.",
    "LOCKDOWN":    "The lab is locked. No entry at the moment.",
    "EM_OPEN":     "The door is open. Please leave calmly.",
}
# door identity -> how to say the name
NAMES = {
    "USER1": "Ali",
    "USER2": "Doctor Ramy",
    "USER3": "Nagy",
    "USER4": "Mohamed",
    "USER5": "Engineer Hemaly",
}


def speak(text: str, path: pathlib.Path, voice: str, rate: int) -> None:
    ps = (
        "Add-Type -AssemblyName System.Speech;"
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer;"
        f"$s.SelectVoice('{voice}'); $s.Rate = {rate};"
        "$f = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo("
        f"{RATE}, [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen,"
        " [System.Speech.AudioFormat.AudioChannel]::Mono);"
        f"$s.SetOutputToWaveFile('{path}', $f); $s.Speak('{text}'); $s.SetOutputToNull()"
    )
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], check=True)


def to_u8(path: pathlib.Path) -> bytes:
    with wave.open(str(path), "rb") as w:
        assert w.getframerate() == RATE and w.getsampwidth() == 2 and w.getnchannels() == 1
        pcm = array.array("h", w.readframes(w.getnframes()))
    # Trim silence (below 2 % of full scale) but keep 40 ms either side.
    loud = [i for i, v in enumerate(pcm) if abs(v) > 650]
    if not loud:
        return b""
    pad = RATE // 25
    pcm = pcm[max(0, loud[0] - pad): loud[-1] + pad]
    peak = max(abs(v) for v in pcm) or 1
    k = 2.5                                      # compression: louder speech, softer peaks
    out = []
    for v in pcm:
        y = math.tanh(k * v / peak) / math.tanh(k)   # -1 .. 1, same for every clip
        out.append(max(0, min(255, round(y * 0.98 * 127) + 128)))
    return bytes(out)


def write_text(clips: dict[str, str]) -> None:
    for t in clips.values():
        assert '"' not in t and "\\" not in t, t      # written into C and JSON as is
    lines = ["// GENERATED by tools/door_voice/make_voice.py - do not edit by hand.",
             "// The words of each clip in door_voice.h, same order, for a tablet page",
             "// that says them with its own voice.",
             "#pragma once", '#include "door_voice.h"', "",
             "static const char *const VOICE_TEXT[] = {"]
    lines += [f'  "{t}",  // {cid}' for cid, t in clips.items()]
    lines += ["};",
              "static_assert(sizeof(VOICE_TEXT) / sizeof(VOICE_TEXT[0]) == VOICE_COUNT,",
              '              "door_voice_text.h does not match door_voice.h - run make_voice.py");', ""]
    TEXT_OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(clips)} texts -> {TEXT_OUT}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="Microsoft Zira Desktop")
    ap.add_argument("--rate", type=int, default=-1, help="-10 (slow) .. 10 (fast)")
    ap.add_argument("--text-only", action="store_true",
                    help="only rewrite door_voice_text.h (no speech synthesis)")
    args = ap.parse_args()

    clips = {**PHRASES, **{f"NAME_{k}": v for k, v in NAMES.items()}}
    write_text(clips)
    if args.text_only:
        return
    lines = ["// GENERATED by tools/door_voice/make_voice.py - do not edit by hand.",
             f"// Voice: {args.voice}, rate {args.rate}, {RATE} Hz, 8-bit unsigned PCM.", "#pragma once",
             "#include <stdint.h>", f"constexpr uint32_t VOICE_RATE = {RATE};", ""]
    table, total = [], 0
    with tempfile.TemporaryDirectory() as tmp:
        for cid, text in clips.items():
            wav = pathlib.Path(tmp) / f"{cid}.wav"
            speak(text.replace("'", "''"), wav, args.voice, args.rate)
            data = to_u8(wav)
            total += len(data)
            print(f"{cid:12s} {len(data) / RATE:5.2f} s  {len(data):6d} B  {text}")
            body = ",".join(str(b) for b in data)
            lines.append(f"static const uint8_t VOICE_DATA_{cid}[{len(data)}] = {{{body}}};")
            table.append(cid)
    lines += ["", "struct VoiceClip { const uint8_t *data; uint32_t len; };",
              "enum VoiceId : uint8_t {"] + [f"  VOICE_{c}," for c in table] + ["  VOICE_COUNT", "};",
              "static const VoiceClip VOICE_CLIPS[VOICE_COUNT] = {"] + \
             [f"  {{VOICE_DATA_{c}, sizeof(VOICE_DATA_{c})}}," for c in table] + ["};", ""]
    # Name clip per door identity (USERn), or VOICE_COUNT when there is none.
    lines.append("inline uint8_t voiceNameFor(const char *subject) {")
    for k in NAMES:
        lines.append(f'  if (!strcmp(subject, "{k}")) return VOICE_NAME_{k};')
    lines += ["  return VOICE_COUNT;", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\n{len(table)} clips, {total / 1024:.0f} KiB of flash -> {OUT}")


if __name__ == "__main__":
    main()
